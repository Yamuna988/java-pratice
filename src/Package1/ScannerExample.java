package Package1;
import java.util.*;
public class ScannerExample {
       public static void main(String[] args)
       {
    	   	Scanner s = new Scanner(System.in);
    	   	System.out.println("Enter a value:");
    	   	int a = s.nextInt();
    	   	System.out.println("Enter b value:");
    	   	int b = s.nextInt();
    	   	System.out.println(a+b);
       }
}
